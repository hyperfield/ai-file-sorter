#pragma once

#include <QJsonArray>
#include <QJsonObject>
#include <cstdint>
#include <filesystem>
#include <memory>
#include <span>
#include <stdexcept>
#include <string>
#include <string_view>
#include <vector>

/** @brief Explicit, private capture of local inference inputs at the decode boundary. */
class InferenceAudit {
public:
    /** @brief Capture failures must not be interpreted as GPU failures or silently ignored. */
    class Error : public std::runtime_error {
    public:
        /** @brief Construct an audit error. @param message Failure description without prompt contents. */
        explicit Error(const std::string& message) : std::runtime_error(message) {}
    };

    /** @brief Actual runtime limits and sampling settings for this inference attempt. */
    struct Runtime {
        int context_tokens;
        int prompt_budget;
        int generation_limit;
        int batch_tokens;
        std::uint32_t seed;
        float temperature;
        float min_p;
        std::string backend;
        int generation_threads{0};
        int batch_threads{0};
    };

    /**
     * @brief Open an owner-only capture when AI_FILE_SORTER_INFERENCE_AUDIT_DIR is set.
     * @param model_path Selected model path.
     * @param system_prompt Original system instructions.
     * @param user_prompt Original user prompt, before any fitting.
     * @param chat_template Exact template obtained from the loaded model, or empty for plain text.
     * @param request_id Shared identity across GPU/CPU retry attempts; assigned only when enabled.
     * @param attempt One-based generation attempt number.
     * @return Capture object, or null when the environment switch is unset/empty.
     * @throws Error When an explicitly requested capture cannot be created securely.
     */
    static std::unique_ptr<InferenceAudit> from_environment(
        const std::string& model_path, std::string_view system_prompt, std::string_view user_prompt,
        std::string_view chat_template, std::string& request_id, int attempt);

    /** @brief Preserve an incomplete marker if a request exits without finalization. */
    ~InferenceAudit();
    /** @brief One capture has exactly one owner. */
    InferenceAudit(const InferenceAudit&) = delete;
    /** @brief Prevent duplicate writers for the same capture. */
    InferenceAudit& operator=(const InferenceAudit&) = delete;

    /** @brief Record actual input/output limits and sampling. @param runtime Resolved runtime settings. */
    void set_runtime(const Runtime& runtime);

    /**
     * @brief Capture a response contract after its native grammar sampler is installed.
     * @param schema Exact requested JSON schema.
     * @param grammar Compiled grammar passed to the sampler.
     */
    void set_response_constraint(std::string_view schema, std::string_view grammar);

    /**
     * @brief Record each tokenized fitting candidate, including rejected oversized candidates.
     * @param user_prompt Candidate user text after optional fitting.
     * @param formatted_prompt Complete chat-template output.
     * @param tokens Exact token IDs produced by the runtime tokenizer.
     * @param detokenized Text reconstructed from those IDs, retaining special tokens.
     */
    void record_fit(std::string_view user_prompt, std::string_view formatted_prompt,
                    std::span<const std::int32_t> tokens, std::string_view detokenized);

    /**
     * @brief Persist the exact prompt slice immediately before llama_decode is called.
     * @param offset Prompt-relative token offset.
     * @param tokens Actual token IDs passed to that decode call.
     */
    void submit_prompt(std::size_t offset, std::span<const std::int32_t> tokens);

    /** @brief Record the return from the most recent prompt decode. @param status Native decode status (zero is success). */
    void prompt_result(int status);

    /**
     * @brief Save the unsanitized generated bytes and termination reason.
     * @param raw_response Bytes returned by token-to-piece conversion, before whitespace trimming.
     * @param stop_reason EOG, token limit, cancellation, or backend error.
     * @param generated_tokens Number of sampled, non-EOG tokens represented by the response.
     */
    void record_generation(std::string_view raw_response, std::string_view stop_reason, int generated_tokens);

    /** @brief Finalize a returned response. @param response Text returned to the caller after optional sanitization. */
    void finish(std::string_view response);

    /** @brief Preserve an unsuccessful attempt. @param message Failure description. */
    void fail(std::string_view message);

private:
    /** @brief Initialize an attempt. @param directory Private request directory. @param request_id Retry identity. @param attempt Attempt number. */
    InferenceAudit(const std::filesystem::path& directory, const std::string& request_id, int attempt);
    /** @brief Atomically checkpoint the capture, failing explicitly on storage errors. */
    void persist() const;
    /** @brief Recompute delivery completeness from accepted, ordered decode chunks. */
    void update_verdict();

    std::filesystem::path file_;
    QJsonObject record_;
    QJsonArray fits_;
    QJsonArray chunks_;
    std::vector<std::int32_t> expected_;
    std::string original_user_;
    std::size_t decoded_count_{0};
    bool all_chunks_match_{true};
    bool finalized_{false};
};
